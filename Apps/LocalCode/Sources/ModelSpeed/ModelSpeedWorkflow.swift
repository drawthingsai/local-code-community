protocol ModelSpeedWorkflowDelegate: AnyObject {
  func modelSpeedWorkflowDidRequestClose(_ workflow: ModelSpeedWorkflow)
  /// Frees the generation queue for a run of `model` and hands over its text generator.
  func modelSpeedWorkflow(_ workflow: ModelSpeedWorkflow, textGeneratorToRun model: String)
    -> (any TextGenerator)?
}

/// Measures how fast a local model prefills one chunk of prompt and decodes 128 tokens at growing
/// context lengths, with a speedometer for the model's family on the generation queue.
final class ModelSpeedWorkflow: Workflow {
  // The chip without the vendor, such as "M4 Pro" or "A18 Pro".
  private static let chipName: String = {
    guard var name = MTLCreateSystemDefaultDevice()?.name else { return UIDevice.current.model }
    if name.hasPrefix("Apple ") {
      name.removeFirst("Apple ".count)
    }
    if name.hasSuffix(" GPU") {
      name.removeLast(" GPU".count)
    }
    return name
  }()

  weak var delegate: ModelSpeedWorkflowDelegate?

  let viewController = ModelSpeedViewController()
  var viewControllable: UIViewController { viewController }

  // Regenerated by the first run for each model after the system clears it.
  private static var storePath: String {
    let cachesURL =
      FileManager.default.urls(for: .cachesDirectory, in: .userDomainMask).first
      ?? URL(fileURLWithPath: NSTemporaryDirectory())
    return cachesURL.appendingPathComponent("speed_context_cache.sqlite3").path
  }

  // The transcript reads the Python standard library the app bundles.
  private static var libraryURL: URL {
    (Bundle.main.resourceURL ?? Bundle.main.bundleURL).appendingPathComponent(
      "Library/lib/python3.14", isDirectory: true)
  }

  private let workspace: SQLiteWorkspace
  private let queue: DispatchQueue
  private let graph: DynamicGraph
  private let streamContext: StreamContext
  // Starts as the chat's model; choosing another one here leaves the chat's alone.
  private var model: String?
  private var modelSelectWorkflow: ItemSelectWorkflow?
  private var measurements = [ModelSpeedViewController.Measurement]()
  private var speedometer: (any Speedometer)?

  init(
    workspace: SQLiteWorkspace, model: String?, queue: DispatchQueue, graph: DynamicGraph,
    streamContext: StreamContext
  ) {
    self.workspace = workspace
    self.model = model
    self.queue = queue
    self.graph = graph
    self.streamContext = streamContext
    viewController.delegate = self
  }

  deinit {
    speedometer?.stop()
    // The speedometer holds the model's generator, which is released on the generation queue.
    queue.async { [speedometer] in withExtendedLifetime(speedometer) {} }
  }

  /// Starts a run for the page's model, replacing any run in progress.
  func start() {
    speedometer?.stop()
    speedometer = nil
    viewController.setProgress(nil)
    let name =
      model.map { LLMZoo.humanReadableNameForModel($0) } ?? LocalizedString.forKey("unspecified")
    viewController.setModel(name: name, image: ChatWorkflow.modelImage(for: model))
    viewController.subtitle =
      DeviceCapability.numberOfGPUCores.map {
        LocalizedString.format(key: "x_on_y_with_z_gpu_cores", name, Self.chipName, $0)
      } ?? LocalizedString.format(key: "x_on_y", name, Self.chipName)
    let speedometer = model.flatMap { makeSpeedometer(model: $0) }
    speedometer?.delegate = self
    self.speedometer = speedometer
    measurements = []
    viewController.contextLengths = speedometer?.contextLengths ?? []
    // Without a run, the chunk every model's generator prefills by on this device.
    viewController.promptLength =
      speedometer?.promptLength ?? DeviceCapability.chunkedPrefillMaxLength
    viewController.measurements = measurements
    viewController.isRunning = speedometer != nil
    guard let speedometer else { return }
    queue.async { [weak self] in
      // Each chart gets its point as soon as its own pass is over.
      for contextLength in speedometer.contextLengths {
        guard let prefillTokensPerSecond = speedometer.prefillReading(contextLength: contextLength)
        else { break }
        DispatchQueue.main.async {
          self?.speedometer(
            speedometer, didReadPrefill: prefillTokensPerSecond, contextLength: contextLength)
        }
        guard let decode = speedometer.decodeReading(contextLength: contextLength) else { break }
        DispatchQueue.main.async {
          self?.speedometer(
            speedometer, didReadDecode: decode.tokensPerSecond, contextLength: contextLength)
        }
      }
      DispatchQueue.main.async {
        self?.speedometerDidFinish(speedometer)
      }
    }
  }

  private func makeSpeedometer(model: String) -> (any Speedometer)? {
    guard let specification = LLMZoo.specificationForModel(model),
      LLMZoo.isModelDownloaded(specification),
      let textGenerator = delegate?.modelSpeedWorkflow(self, textGeneratorToRun: model)
    else { return nil }
    // Runs think and sample the way the chat does.
    let thinkingBudget = min(
      max(workspace.dictionary["thinking_budget", Int.self] ?? 65_536, 0), 128 * 1024)
    let deterministic =
      (workspace.dictionary["work_attitude", WorkAttitude.self] ?? .deterministic)
      == .deterministic
    switch textGenerator {
    case let textGenerator as Qwen3_5TextGenerator:
      return Qwen3_5Speedometer(
        textGenerator: textGenerator, model: model,
        contextLengths: SpeedometerReading.contextLengths, graph: graph,
        streamContext: streamContext, storePath: Self.storePath, libraryURL: Self.libraryURL,
        thinkingBudget: thinkingBudget, deterministic: deterministic)
    case let textGenerator as DeepSeek4TextGenerator:
      return DeepSeek4Speedometer(
        textGenerator: textGenerator, contextLengths: SpeedometerReading.contextLengths,
        graph: graph, streamContext: streamContext, storePath: Self.storePath,
        libraryURL: Self.libraryURL, thinkingBudget: thinkingBudget, deterministic: deterministic)
    case let textGenerator as DeepSeek4_1TextGenerator:
      return DeepSeek4Speedometer(
        textGenerator: textGenerator, contextLengths: SpeedometerReading.contextLengths,
        graph: graph, streamContext: streamContext, storePath: Self.storePath,
        libraryURL: Self.libraryURL, thinkingBudget: thinkingBudget, deterministic: deterministic)
    default:
      return nil
    }
  }

  private func speedometer(
    _ speedometer: any Speedometer, didReadPrefill tokensPerSecond: Double, contextLength: Int
  ) {
    guard speedometer === self.speedometer else { return }
    measurements.append(
      ModelSpeedViewController.Measurement(
        contextLength: contextLength, prefillTokensPerSecond: tokensPerSecond))
    viewController.measurements = measurements
  }

  private func speedometer(
    _ speedometer: any Speedometer, didReadDecode tokensPerSecond: Double, contextLength: Int
  ) {
    guard speedometer === self.speedometer, measurements.last?.contextLength == contextLength
    else { return }
    measurements[measurements.count - 1].decodeTokensPerSecond = tokensPerSecond
    viewController.measurements = measurements
  }

  private func speedometerDidFinish(_ speedometer: any Speedometer) {
    guard speedometer === self.speedometer else { return }
    self.speedometer = nil
    viewController.isRunning = false
    viewController.setProgress(nil)
    queue.async { withExtendedLifetime(speedometer) {} }
  }

  private func stop() {
    speedometer?.stop()
    viewController.isRunning = false
    viewController.setProgress(nil)
  }
}

extension ModelSpeedWorkflow: SpeedometerDelegate {
  // Arrives on the generation queue.
  func speedometer(_ speedometer: any Speedometer, didUpdate progress: SpeedometerProgress) {
    DispatchQueue.main.async { [weak self] in
      guard let self, speedometer === self.speedometer else { return }
      self.viewController.setProgress(progress)
    }
  }
}

extension ModelSpeedWorkflow: ModelSpeedViewControllerDelegate {
  func modelSpeedViewControllerDidTapStop(_ viewController: ModelSpeedViewController) {
    stop()
  }

  func modelSpeedViewControllerDidTapStartAgain(_ viewController: ModelSpeedViewController) {
    start()
  }

  func modelSpeedViewControllerDidTapDone(_ viewController: ModelSpeedViewController) {
    delegate?.modelSpeedWorkflowDidRequestClose(self)
  }

  func modelSpeedViewController(
    _ viewController: ModelSpeedViewController, didTapShare sourceView: UIView
  ) {
    let activityViewController = UIActivityViewController(
      activityItems: [viewController.resultsImage()], applicationActivities: nil)
    activityViewController.popoverPresentationController?.sourceView = sourceView
    activityViewController.popoverPresentationController?.sourceRect = sourceView.bounds
    viewController.present(activityViewController, animated: true)
  }

  func modelSpeedViewController(
    _ viewController: ModelSpeedViewController, didTapModelSelector sourceView: UIView
  ) {
    // This page keeps its own model, and only local models run here.
    let modelSelectWorkflow = ItemSelectWorkflow(
      userInterfaceIdiom: sourceView.traitCollection.userInterfaceIdiom, cellHeight: 32,
      minimumLineSpacing: 4, workspace: workspace, isSwitchDisplayed: false,
      isDetailSwitchDisplayed: false)
    self.modelSelectWorkflow = modelSelectWorkflow
    modelSelectWorkflow.delegate = self
    modelSelectWorkflow.updateTitle(title: LocalizedString.forKey("model"))
    modelSelectWorkflow.setViewModels(
      [ChatWorkflow.localModelSection(selectedModel: model, workspace: workspace)], flag: nil)
    if let popoverPresentationController = modelSelectWorkflow.viewControllable
      .popoverPresentationController
    {
      popoverPresentationController.sourceView = sourceView
      popoverPresentationController.sourceRect = sourceView.bounds
      popoverPresentationController.permittedArrowDirections = .down
      popoverPresentationController.popoverLayoutMargins = UIEdgeInsets(
        top: 0, left: 12, bottom: 0, right: 12)
    }
    viewController.present(modelSelectWorkflow.viewControllable, animated: true)
    DispatchQueue.main.async { [model] in
      if let model {
        modelSelectWorkflow.selectItem(at: .identifier(model))
      }
    }
  }
}

extension ModelSpeedWorkflow: ItemSelectWorkflowDelegate {
  func didSelectItem(
    item: ItemViewModel.ItemIdentifier, section: ItemDisplaySectionIdentity,
    workflow: ItemSelectWorkflow
  ) {
    guard workflow === modelSelectWorkflow else { return }
    workflow.viewControllable.dismiss(animated: true)
    modelSelectWorkflow = nil
    guard case .identifier(let identifier as String) = item, identifier != model else { return }
    model = identifier
    start()
  }

  func didTapTrash(item: ItemViewModel.ItemIdentifier, workflow: ItemSelectWorkflow) {
  }

  func didSelectShowAll(showAll: Bool, workflow: ItemSelectWorkflow) {
  }

  func didSelectShowDetails(showDetails: Bool, workflow: ItemSelectWorkflow) {
  }

  func didDismiss(workflow: ItemSelectWorkflow) {
    guard workflow === modelSelectWorkflow else { return }
    modelSelectWorkflow = nil
  }
}
